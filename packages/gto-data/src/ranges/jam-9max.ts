/**
 * 9-max MTT jam-or-fold (open-shove) ranges at 10BB and 20BB.
 *
 * Short-stack tournament play collapses to push/fold: at ≤10BB every
 * open is an all-in, and at ~20BB the unexploitable open-shove range
 * is the standard late-game reference (min-raising exists but the jam
 * chart is the canonical study tool).
 *
 * Numbers follow the established chipEV Nash equilibrium tables
 * (Holdem Resources Calculator / SnapShove-family published charts),
 * ante-adjusted MTT convention: monotonic widening from UTG to SB,
 * with the 10BB ranges roughly twice as wide as 20BB at every seat.
 * Pure Nash — frequencies are 0 or 1, no mixing.
 *
 * Emitted by build-preflop.ts as 9max_{10,20}bb_jam_{POS}.json using
 * the same { raise, fold } shape as RFI charts (raise = all-in) so the
 * chart viewer stays uniform; the UI labels the action 올인 by depth.
 */

type ComboFreq = Record<string, number>;

function jam(combos: readonly string[]): ComboFreq {
  const out: ComboFreq = {};
  for (const c of combos) out[c] = 1;
  return out;
}

